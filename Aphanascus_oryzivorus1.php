<h2><em>Aphanascus oryzivorus </em><span>Stephenson, 1924</span></h2>
<ul class="list-4">
  <li>Unpigmented, grey in colour owing to the intestine and its contents showing through the body-wall.</li>
  <li>Setae closely paired.</li>
  <li>Prostomium zygolobous.</li>
  <li>Dorsal pores absent.</li>
  <li>On segment xvii are a pair of small round prominent papillae, teat like, bearing the prostatic pores, which are just external to the line of setae b.</li>
  <li>One pair of spermathecal pores are in groove 8/9, on small papillae, in line with setae b.</li>
  <li>Gizzard vestigial, in vii.</li>
  <li>Metandric; testes and funnels are free in segment xi.</li>
  <li>Type locality is found in Anaikomban paddy field in Kollengode, Kerala, India and is endemic.</li>
</ul>
