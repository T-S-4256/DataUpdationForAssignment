<h2><em>Aiyeriella </em><span>Narayanan &amp; Julka, 2025</span></h2>
<ul class="list-4">
<li>Combined male and prostatic pores, paired at posterior ends of fine seminal grooves on segment xviii.</li>
<li>Setae lumbricine.</li>
<li>Single large oesophageal gizzard, in segment v.</li>
<li>Oesophageal calciferous glands or calciferous dilations absent.</li>
<li>Supra-intestinal glands, typhlosole, and intestinal caeca absent.</li>
<li>Micromeronephridia astomate, exonephric paired tufts in ii-x.</li>
<li>Several avesiculate, exonephric on the body wall in xi, and posteriad segments.</li>
<li>Prostates tubuloracemose, elongated, strap-shaped, paired.</li>
<li>Penial setae absent.</li>
<li>Two species recorded from India <em>viz</em>.,</li>
</ul>
