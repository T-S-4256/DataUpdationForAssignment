<h2><em>Dashiella </em><span> khandalaensis Julka, 1988</span></h2>
<ul class="list-4">
    <li>Combined male and prostatic pores paired on xvii; seminal grooves absent.</li>
    <li>Female pore single median pre-setal on xiv.</li>
    <li>Oesophagus with 2 gizzards in v-vi.</li>
    <li>Three pairs of discrete extramural calciferous glands in xi-xiii.</li>
    <li>Supra-intestinal glands absent.</li>
    <li>Typhlosole lamelliform.</li>
    <li>Genital markings circular to oval, paired, presetal on xvi and xvii at ab.</li>
    <li>Spermathecal pores in paired batteries of 1-4 (polythecal) on vi/vii/viii</li>
    <li>Single species found in India.</li>
    <li>Type locality is Khandala, Maharashtra, India and is endemic.</li>
</ul>