<h2><em>Argilophilus </em><span>Eisen, 1893</span></h2>
<ul class="list-4">
    <li>Male pores in xviii, xix or xx.</li>
    <li>Three pairs kidney-shaped extramural calciferous glands.</li>
    <li>Holoic.</li>
    <li>Lumbricine.</li>
    <li>Prostate tubular.</li>
    <li>Dorsal pores present behind clitellum.</li>
    <li>Intestinal origin xiv, xv, xvi, xvii or xviii.</li>
    <li>Spermathecae 1,2, 3, 4, 5, 6 or 7 pairs in some or all of vi-xii.</li>
    <li>Twenty three species recorded from India <em>viz</em>.,</li>
