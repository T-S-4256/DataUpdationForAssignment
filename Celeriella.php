<h2><em>Celeriella </em><span> Gates, 1958</span></h2>
<ul class="list-4">
    <li>Combined male and prostatic pores paired, on xviii.</li>
    <li>Female pores paired presetal on xiv.</li>
    <li>Oesophagus with a single gizzard in vi.</li>
    <li>Discrete calciferous gland absent but with calciferous lamellae in enlarged portions or pouches in xiii-xiv.
    </li>
    <li>Intestinal caecae, supra-intestinal glands and typhlosole absent.</li>
    <li>Spermathecal pores paired in 7/8 or 7/8/9.</li>
    <li>Stomate paired enteronephric mega-meronephridia found in caudal segments.</li>
    <li>Holandric testes, male funnel free in x and xi.</li>
    <li>Prostates paired in xviii, extending posteriorly through several segments, vasa deferentia on each side joins
        the prostatic duct entally.</li>
    <li>Penial setae absent.</li>
    <li>Seven species recorded from India <em>viz</em>., </li>
</ul>
